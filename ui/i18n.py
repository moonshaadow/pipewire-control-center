def get_system_lang():
    lang = os.environ.get('LANG', '') or locale.getdefaultlocale()[0] or 'en'
    return lang.split('_')[0] if '_' in lang else lang


class I18n:
    _instance = None
    
    def __init__(self):
        self._lang = 'auto'
        self._ui_config = None
    
    @classmethod
    def instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance
    
    def set_ui_config(self, ui_config):
        self._ui_config = ui_config
    
    def set_lang(self, lang):
        self._lang = lang
    
    def get_lang(self):
        if self._lang == 'auto':
            if self._ui_config is not None:
                return self._ui_config.get_lang()
            return get_system_lang()
        return self._lang
    
    def tr(self, key):
        lang = self.get_lang()
        return T.get(lang, T['en']).get(key, key)
